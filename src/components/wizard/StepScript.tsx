import { useState, useEffect } from "react";
import { useParams, useNavigate } from "react-router";
import { trpc } from "@/providers/trpc";
import { motion } from "framer-motion";
import { toast } from "sonner";
import {
  Sparkles,
  ChevronRight,
  ChevronLeft,
  RefreshCw,
  Check,
  AlertTriangle,
  Loader2,
  Trash2,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { detectGibberish } from "@/lib/gibberish";

export default function StepScript() {
  const { projectId } = useParams<{ projectId: string }>();
  const navigate = useNavigate();
  const projectIdNum = Number(projectId) || 0;
  const [scripts, setScripts] = useState<Record<number, string>>({});
  const [isGenerating, setIsGenerating] = useState(false);
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);
  const [scriptError, setScriptError] = useState<string | null>(null);

  const utils = trpc.useUtils();

  const { data: project, isLoading } = trpc.project.getById.useQuery(
    { id: projectIdNum },
    { enabled: projectIdNum > 0 }
  );

  const generateScript = trpc.ai.generateScript.useMutation();
  const regenerateStepScript = trpc.ai.regenerateStepScript.useMutation();
  const updateStep = trpc.step.update.useMutation();
  const deleteStep = trpc.step.delete.useMutation();

  const [regeneratingStepId, setRegeneratingStepId] = useState<number | null>(null);

  const handleDeleteStep = async (stepId: number) => {
    try {
      await deleteStep.mutateAsync({ id: stepId });
      // Remove from local state
      setScripts((prev) => {
        const next = { ...prev };
        delete next[stepId];
        return next;
      });
      // Refresh project data
      await utils.project.getById.invalidate({ id: projectIdNum });
    } catch (err) {
      console.error("Failed to delete step:", err);
    }
  };

  const handleGenerate = async () => {
    setIsGenerating(true);
    try {
      const result = await generateScript.mutateAsync({ projectId: projectIdNum });

      // If the mutation returned scripts, use them directly
      if (result?.scripts && Array.isArray(result.scripts) && project?.steps) {
        const newScripts: Record<number, string> = {};
        project.steps.forEach((s, i) => {
          newScripts[s.id] = result.scripts[i] || "";
        });
        setScripts(newScripts);
      }

      // Also invalidate the cache so the query re-fetches with updated DB values
      await utils.project.getById.invalidate({ id: projectIdNum });
    } catch (err) {
      console.error("Script generation failed:", err);
    }
    setIsGenerating(false);
  };

  // Sync scripts from project data whenever it changes (initial load or after invalidation)
  useEffect(() => {
    if (project?.steps) {
      const currentScripts: Record<number, string> = {};
      let allEmpty = true;

      project.steps.forEach((s) => {
        const script = s.userEditedScript || s.aiScript || "";
        currentScripts[s.id] = script;
        if (script.trim().length > 0) {
          allEmpty = false;
        }
      });

      setScripts(currentScripts);

      // Auto-generate on first load if all scripts are empty
      if (allEmpty && !hasAutoGenerated && !isGenerating) {
        setHasAutoGenerated(true);
        handleGenerate();
      }
    }
  }, [project]);

  const handleRegenerateStep = async (stepId: number) => {
    const step = project?.steps?.find((s) => s.id === stepId);
    if (!step?.description || !step.description.trim() || /^scene\s+\d+$/i.test(step.description.trim())) {
      toast.error(`Scene ${step?.order || ""} has no description. Please write a description in Step 2 before regenerating script.`);
      return;
    }

    setRegeneratingStepId(stepId);
    try {
      const result = await regenerateStepScript.mutateAsync({ stepId });
      const newScript = result?.script || "";
      setScripts((prev) => ({ ...prev, [stepId]: newScript }));
    } catch (err) {
      console.error("Failed to regenerate step script:", err);
    } finally {
      setRegeneratingStepId(null);
    }
  };

  const handleUpdateScript = (stepId: number, value: string) => {
    setScripts((prev) => ({ ...prev, [stepId]: value }));
  };

  const handleContinue = async () => {
    // Block gibberish scripts from being saved / moved forward.
    for (const [stepId, script] of Object.entries(scripts)) {
      const trimmed = (script || "").trim();
      if (trimmed) {
        const g = detectGibberish(trimmed);
        if (g.isGibberish) {
          setScriptError(
            `Step ${stepId} script looks like random text — please edit it to be a real narration.`
          );
          return;
        }
      }
    }
    setScriptError(null);
    for (const [stepId, script] of Object.entries(scripts)) {
      await updateStep.mutateAsync({
        id: Number(stepId),
        userEditedScript: script,
      });
    }
    navigate(`/create/${projectIdNum}/preview`);
  };

  const totalWords = Object.values(scripts).reduce(
    (acc, s) => acc + (s?.split(/\s+/).length || 0),
    0
  );
  const estimatedDuration = Math.round(totalWords / 150 * 60);

  if (isLoading) {
    return (
      <div className="flex items-center justify-center py-20">
        <Loader2 className="w-8 h-8 animate-spin text-[var(--sketch-fg)]" />
      </div>
    );
  }

  return (
    <div className="w-full">
      <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }}>
        <div className="flex items-start justify-between">
          <div className="relative">
            <span className="font-mono text-xs text-[var(--sketch-fg-muted)] uppercase tracking-widest bg-[#FBBF24]/20 px-2 py-1 sketch-border-sm inline-block">
              Step 3 of 7
            </span>
            <span className="font-hand text-lg text-[var(--sketch-fg-muted)] absolute -top-6 left-32 rotate-[-4deg] animate-float hidden sm:block">
              Make it sound natural! 📝
            </span>
            <h2 className="font-body font-bold text-3xl mt-3 tracking-tight text-[var(--sketch-fg)]">
              Review your script
            </h2>
          </div>
          <div className="flex items-center gap-2 px-3 py-1.5 border-2 border-[var(--sketch-border-color)] bg-[var(--sketch-card-bg)] shadow-[3px_3px_0px_0px_#FBBF24]">
            <span className="relative flex h-2 w-2">
              <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-emerald-400 opacity-75"></span>
              <span className="relative inline-flex rounded-full h-2 w-2 bg-emerald-500"></span>
            </span>
            <span className="font-mono text-xs font-medium text-[var(--sketch-fg)] uppercase tracking-wider">AI Online</span>
          </div>
        </div>
        <p className="font-body text-[var(--sketch-fg-muted)] mt-2">
          Edit the AI-generated narration for each step. Keep it concise and clear.
        </p>

        {project?.steps && (
          <div className="mt-4 sketch-card p-3 bg-[#FBBF24]/5 border-[#FBBF24] inline-flex items-center gap-3">
            <Check className="w-4 h-4 text-[var(--sketch-fg)]" />
            <span className="font-body text-sm text-[var(--sketch-fg)]">
              {totalWords} words across {project.steps.length} steps
              {estimatedDuration > 0 && ` — approx. ${estimatedDuration}s of video`}
            </span>
          </div>
        )}

        <div id="script-timeline" className="mt-6 space-y-4 scroll-mt-6">
          {project?.steps?.map((step, index) => {
            const script = scripts[step.id] || "";
            const wordCount = script.split(/\s+/).filter(Boolean).length;
            const isLong = wordCount > 40;
            const isShort = wordCount < 8 && wordCount > 0;

            return (
              <motion.div
                key={step.id}
                initial={{ opacity: 0, y: 10 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ delay: index * 0.05 }}
                className="sketch-card p-4 bg-[var(--sketch-card-bg)]"
              >
                <div className="flex items-start gap-3">
                  <div className="w-12 h-12 bg-[var(--sketch-card-bg)] border-2 border-[var(--sketch-border-color)] flex-shrink-0 flex items-center justify-center sketch-border-sm overflow-hidden">
                    {step.screenshotPath ? (
                      <img
                        src={step.screenshotPath}
                        alt=""
                        className="w-full h-full object-cover"
                      />
                    ) : (
                      <span className="font-hand text-lg text-[var(--sketch-fg-subtle)]">
                        {index + 1}
                      </span>
                    )}
                  </div>
                  <div className="flex-1">
                    <div className="flex items-center justify-between mb-2">
                      <span className="font-mono text-xs text-[var(--sketch-fg-subtle)]">
                        Step {index + 1}
                      </span>
                      <div className="flex items-center gap-3">
                        <span className="font-mono text-xs text-[var(--sketch-fg-subtle)]">
                          {wordCount} words
                        </span>
                        {isLong && (
                          <span className="flex items-center gap-1 text-xs font-mono text-amber-600">
                            <AlertTriangle className="w-3 h-3" />
                            Long
                          </span>
                        )}
                        {isShort && (
                          <span className="flex items-center gap-1 text-xs font-mono text-amber-600">
                            <AlertTriangle className="w-3 h-3" />
                            Short
                          </span>
                        )}
                      </div>
                    </div>
                    <textarea
                      value={script}
                      onChange={(e) =>
                        handleUpdateScript(step.id, e.target.value)
                      }
                      rows={3}
                      className={`sketch-input resize-none text-sm ${
                        script.trim() && detectGibberish(script).isGibberish
                          ? "border-red-500"
                          : ""
                      }`}
                    />
                    {script.trim() && detectGibberish(script).isGibberish && (
                      <p className="font-body text-xs text-amber-600 mt-1 flex items-center gap-1">
                        <AlertTriangle className="w-3 h-3" />
                        {detectGibberish(script).reason}
                      </p>
                    )}
                    <div className="mt-2 flex justify-between">
                      <button
                        onClick={() => handleDeleteStep(step.id)}
                        className="font-hand text-sm text-[var(--sketch-fg-subtle)] hover:text-red-500 flex items-center gap-1 transition-colors"
                      >
                        <Trash2 className="w-3 h-3" />
                        Remove
                      </button>
                      <button
                        onClick={() => handleRegenerateStep(step.id)}
                        disabled={regeneratingStepId === step.id}
                        className="font-hand text-sm text-[var(--sketch-fg-subtle)] hover:text-[var(--sketch-fg)] flex items-center gap-1 transition-colors disabled:opacity-50"
                      >
                        {regeneratingStepId === step.id ? (
                          <Loader2 className="w-3 h-3 animate-spin" />
                        ) : (
                          <RefreshCw className="w-3 h-3" />
                        )}
                        {regeneratingStepId === step.id ? "Regenerating..." : "Regenerate"}
                      </button>
                    </div>
                  </div>
                </div>
              </motion.div>
            );
          })}
        </div>

        {scriptError && (
          <div className="mt-4 sketch-card p-3 bg-red-500/10 border-red-500 flex items-start gap-2">
            <AlertTriangle className="w-4 h-4 text-red-600 shrink-0 mt-0.5" />
            <span className="font-body text-sm text-red-600">{scriptError}</span>
          </div>
        )}

        <div className="mt-6 flex gap-3">
          <Button
            variant="ghost"
            type="button"
            onClick={() => navigate(`/create/${projectIdNum}/upload`)}
            className="sketch-btn-ghost flex-1"
          >
            <ChevronLeft className="w-4 h-4" />
            Back
          </Button>
          <Button
            variant="ghost"
            onClick={handleGenerate}
            disabled={isGenerating}
            className="sketch-btn-ghost flex-1"
          >
            {isGenerating ? (
              <span className="flex items-center gap-2 justify-center">
                <Loader2 className="w-4 h-4 animate-spin" />
                Generating...
              </span>
            ) : (
              <span className="flex items-center gap-2 justify-center">
                <Sparkles className="w-4 h-4" />
                Regenerate All
              </span>
            )}
          </Button>
          <Button
            onClick={handleContinue}
            disabled={updateStep.isPending}
            className="sketch-btn-primary flex-[2]"
          >
            <span className="flex items-center gap-2 justify-center">
              These look good
              <ChevronRight className="w-4 h-4" />
            </span>
          </Button>
        </div>
      </motion.div>
    </div>
  );
}
